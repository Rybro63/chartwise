#!/usr/bin/env python3
"""Measures how often the safety check catches bad drafts (mutation testing).

For every synthetic patient generated by Synthea (tools/synthea/generate.sh), this:

1. Builds a visit transcript with the same generator the demo uses.
2. Builds a clean draft from it: one that only says what the transcript and record support.
3. Derives bad drafts by injecting one known error of each kind below.
4. Runs the real safety check on every draft and counts what it catches.

A case counts as caught when the check raises a high-severity flag naming the injected drug.
Clean drafts, including tricky-but-correct ones, measure the false-positive rate.

    python eval/run_safety_eval.py --synthea ../../tools/synthea/output/fhir --out ../../docs/results

Categories marked out_of_scope are errors the check does not claim to detect. They are measured
anyway so the report shows the boundary instead of hiding it.
"""

import argparse
import importlib.util
import json
import random
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from note_worker import safety  # noqa: E402
from note_worker.drug_lexicon import BRANDS, GENERICS, canonical  # noqa: E402
from note_worker.soap import SoapDraft  # noqa: E402

_spec = importlib.util.spec_from_file_location("transcripts", ROOT.parents[1] / "tools" / "transcripts" / "generate.py")
transcripts = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(transcripts)

CATEGORIES = {
    # name: (should_flag, in_scope, description)
    "clean": (False, True, "Draft supported by the transcript and record"),
    "clean_brand_equivalence": (False, True, "Patient says a brand name, draft uses the generic"),
    "clean_transcription_typo": (False, True, "Transcript misspells a drug the draft spells correctly"),
    "clean_allergy_mention": (False, True, "Draft documents a drug allergy from the record (found in real Claude output)"),
    "hallucinated_generic": (True, True, "Draft starts a generic drug nobody mentioned"),
    "hallucinated_brand": (True, True, "Draft starts a brand-name drug nobody mentioned"),
    "hallucinated_unlisted": (True, True, "Drug added to the plan text but left off the model's medication list"),
    "hallucinated_in_history": (True, True, "Draft claims in the subjective that the patient takes an unmentioned drug"),
    "allergy_conflict": (True, True, "Draft starts a drug the patient is allergic to (by class)"),
    "misspelled_hallucination": (True, False, "Unmentioned drug, misspelled in the draft"),
    "unknown_drug": (True, False, "Unmentioned drug that is not in the lexicon (newer agents)"),
    "wrong_dose": (True, False, "Correct drug, wrong dose"),
}

# Real drugs deliberately absent from the lexicon, to measure its coverage limit.
NOT_IN_LEXICON = ["tirzepatide", "finerenone", "vericiguat", "inclisiran", "mavacamten", "sotagliflozin"]


@dataclass
class Case:
    category: str
    patient: str
    draft: SoapDraft
    transcript: str
    medications: list[str]
    allergies: list[str]
    target: str | None  # injected drug (canonical) the flag must name


def load_profiles(synthea_dir: Path) -> list[dict]:
    profiles = []
    for f in sorted(synthea_dir.glob("*.json")):
        if f.name.startswith(("hospitalInformation", "practitionerInformation")):
            continue
        resources = [e["resource"] for e in json.loads(f.read_text())["entry"]]
        conditions = [transcripts.display(r["code"]) for r in resources if r["resourceType"] == "Condition"
                      and r.get("clinicalStatus", {}).get("coding", [{}])[0].get("code") == "active"]
        meds = [transcripts.display(r.get("medicationCodeableConcept")) for r in resources
                if r["resourceType"] == "MedicationRequest" and r.get("status") == "active"]
        allergies = [transcripts.display(r["code"]) for r in resources if r["resourceType"] == "AllergyIntolerance"]
        pid = next(r["id"] for r in resources if r["resourceType"] == "Patient")
        profiles.append({"id": pid, "conditions": [c for c in conditions if c], "medications": [m for m in meds if m],
                         "allergies": [a for a in allergies if a]})
    return profiles


def clean_draft(transcript: str, profile: dict) -> tuple[dict, list[dict]]:
    """What a faithful model would write: only what the transcript says, grounded in the record."""
    said = [line.split(":", 1)[1].strip() for line in transcript.splitlines() if line.startswith("Patient:")]
    doctor = [line.split(":", 1)[1].strip() for line in transcript.splitlines() if line.startswith("Doctor:")]
    vitals = next((d for d in doctor if "blood pressure" in d), "Vitals not documented.")
    discussed = [w for w in (transcripts.generic(m) for m in profile["medications"]) if w and f"taking the {w}" in transcript]
    otc = [d for d in transcripts.OTC if d in transcript]

    plan = [f"Continue {d} at the current dose." for d in discussed]
    plan += [f"{d.capitalize()} as needed, as the patient reports." for d in otc]
    plan.append("Follow up as discussed; return sooner if symptoms worsen.")
    meds = [{"name": d, "status": "continued"} for d in discussed] + [{"name": d, "status": "mentioned"} for d in otc]
    sections = {
        "subjective": " ".join(said[:3]),
        "objective": vitals,
        "assessment": "; ".join(c.split(" (")[0] for c in profile["conditions"][:2]) or "Follow-up visit.",
        "plan": " ".join(plan),
    }
    return sections, meds


def ungrounded_drugs(transcript: str, profile: dict, allergies: list[str]) -> list[str]:
    text = (transcript + " " + " ".join(profile["medications"]) + " " + " ".join(allergies)).lower()
    return sorted(g for g in GENERICS if g not in text and not any(b in text for b, gen in BRANDS.items() if gen == g))


def misspell(word: str, rng: random.Random) -> str:
    i = rng.randrange(1, len(word) - 1)
    return word[:i] + word[i + 1:]  # drop one interior letter, e.g. warfarin -> warfrin


def build_cases(profiles: list[dict], visits_per_patient: int, seed: int) -> list[Case]:
    rng = random.Random(seed)
    cases: list[Case] = []
    for profile in profiles:
        for _ in range(visits_per_patient):
            transcript = transcripts.transcript(profile, rng)
            sections, meds = clean_draft(transcript, profile)
            allergies = profile["allergies"]
            pool = ungrounded_drugs(transcript, profile, allergies)

            def add(category, sections_=None, meds_=None, transcript_=None, allergies_=None, target=None):
                cases.append(Case(category, profile["id"],
                                  SoapDraft.model_validate({**(sections_ or sections), "medications_mentioned": meds_ if meds_ is not None else meds}),
                                  transcript_ or transcript, profile["medications"], allergies_ if allergies_ is not None else allergies,
                                  target))

            add("clean")

            brand, gen = rng.choice([("Tylenol", "acetaminophen"), ("Advil", "ibuprofen"), ("Claritin", "loratadine")])
            add("clean_brand_equivalence",
                {**sections, "plan": sections["plan"] + f" {gen.capitalize()} as needed."},
                meds + [{"name": gen, "status": "mentioned"}],
                transcript + f"\nPatient: I've been taking {brand} now and then.")

            add("clean_transcription_typo",
                {**sections, "plan": sections["plan"] + " Ibuprofen 400 mg as needed for pain."},
                meds + [{"name": "ibuprofen", "status": "mentioned"}],
                transcript + "\nPatient: The ibuprofin helps a little.")

            allergen = rng.choice(["Penicillin V", "Aspirin", "Sulfamethoxazole"])
            add("clean_allergy_mention",
                {**sections, "subjective": sections["subjective"] + f" Documented allergy to {allergen.lower()}; not discussed today."},
                allergies_=allergies + [allergen])

            drug = rng.choice(pool)
            add("hallucinated_generic", {**sections, "plan": sections["plan"] + f" Start {drug} 5 mg daily."},
                meds + [{"name": drug, "status": "started"}], target=drug)

            brands = [b for b, g in BRANDS.items() if g in pool]
            b = rng.choice(brands)
            add("hallucinated_brand", {**sections, "plan": sections["plan"] + f" Start {b.capitalize()} as directed."},
                meds + [{"name": b.capitalize(), "status": "started"}], target=canonical(b))

            drug = rng.choice(pool)
            add("hallucinated_unlisted", {**sections, "plan": sections["plan"] + f" Add {drug} 10 mg at bedtime."},
                meds, target=drug)

            drug = rng.choice(pool)
            add("hallucinated_in_history", {**sections, "subjective": sections["subjective"] + f" Takes {drug} daily."},
                meds, target=drug)

            abx = rng.choice(["amoxicillin", "ampicillin"])
            add("allergy_conflict", {**sections, "plan": sections["plan"] + f" Start {abx} 500 mg three times daily."},
                meds + [{"name": abx, "status": "started"}],
                transcript + f"\nDoctor: I'll send in {abx} for the infection.",
                allergies + ["Allergy to penicillin"], target=abx)

            drug = rng.choice([d for d in pool if len(d) >= 7])
            typo = misspell(drug, rng)
            add("misspelled_hallucination", {**sections, "plan": sections["plan"] + f" Start {typo} 5 mg daily."},
                meds + [{"name": typo, "status": "started"}], target=typo)

            drug = rng.choice(NOT_IN_LEXICON)
            add("unknown_drug", {**sections, "plan": sections["plan"] + f" Start {drug} as directed."},
                meds + [{"name": drug, "status": "started"}], target=drug)

            if meds and meds[0]["status"] == "continued":
                d = meds[0]["name"]
                add("wrong_dose", {**sections, "plan": sections["plan"].replace(f"Continue {d} at the current dose.",
                                                                                 f"Continue {d} 400 mg twice daily.")},
                    target=d)
    return cases


def caught(case: Case, flags: list) -> bool:
    high = [f for f in flags if f.severity == "high"]
    if case.target is None:
        return bool(high)
    return any(canonical(f.subject) == case.target or f.subject.lower() == case.target for f in high)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--synthea", default=str(ROOT.parents[1] / "tools" / "synthea" / "output" / "fhir"))
    ap.add_argument("--visits", type=int, default=4, help="visits per patient")
    ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--out", default=str(ROOT.parents[1] / "docs" / "results"))
    args = ap.parse_args()

    profiles = load_profiles(Path(args.synthea))
    if not profiles:
        sys.exit("No Synthea bundles found. Run tools/synthea/generate.sh first.")
    cases = build_cases(profiles, args.visits, args.seed)

    by_cat: dict[str, list[bool]] = defaultdict(list)
    for case in cases:
        flags = safety.check(case.draft, transcript=case.transcript, record_medications=case.medications,
                             allergies=case.allergies)
        by_cat[case.category].append(caught(case, flags))

    rows = []
    for cat, (should_flag, in_scope, desc) in CATEGORIES.items():
        results = by_cat.get(cat, [])
        rows.append({"category": cat, "description": desc, "should_flag": should_flag, "in_scope": in_scope,
                     "cases": len(results), "flagged": sum(results),
                     "rate": round(sum(results) / len(results), 4) if results else None})

    bad_in_scope = [r for r in rows if r["should_flag"] and r["in_scope"]]
    clean = [r for r in rows if not r["should_flag"]]
    tp = sum(r["flagged"] for r in bad_in_scope)
    fp = sum(r["flagged"] for r in clean)
    summary = {
        "patients": len(profiles),
        "cases": len(cases),
        "recall_in_scope": round(tp / sum(r["cases"] for r in bad_in_scope), 4),
        "false_positive_rate": round(fp / sum(r["cases"] for r in clean), 4),
        "precision_in_scope": round(tp / (tp + fp), 4) if tp + fp else None,
    }

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "safety-eval.json").write_text(json.dumps({"summary": summary, "categories": rows}, indent=2) + "\n")

    print(f"{summary['cases']} drafts from {summary['patients']} synthetic patients")
    print(f"recall (in-scope errors caught): {summary['recall_in_scope']:.1%}")
    print(f"false-positive rate (clean drafts flagged): {summary['false_positive_rate']:.1%}")
    print(f"\n{'category':<28}{'cases':>7}{'flagged':>9}{'rate':>8}  scope")
    for r in rows:
        print(f"{r['category']:<28}{r['cases']:>7}{r['flagged']:>9}{(r['rate'] or 0):>8.1%}  "
              f"{'in' if r['in_scope'] else 'OUT'}{'' if r['should_flag'] else ' (clean: lower is better)'}")

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not installed; skipping chart")
        return
    fig, ax = plt.subplots(figsize=(10, 4.8))
    labels = [r["category"].replace("_", " ") for r in rows]
    colors = ["#7a8699" if not r["should_flag"] else ("#1f6feb" if r["in_scope"] else "#c9ced6") for r in rows]
    bars = ax.barh(labels, [r["rate"] or 0 for r in rows], color=colors)
    ax.bar_label(bars, labels=[f"{(r['rate'] or 0):.0%}  ({r['flagged']}/{r['cases']})" for r in rows], padding=4, fontsize=8)
    ax.invert_yaxis()
    ax.set_xlim(0, 1.3)
    ax.set_xticks([0, 0.25, 0.5, 0.75, 1.0], ["0%", "25%", "50%", "75%", "100%"])
    ax.set_xlabel("share of drafts flagged")
    ax.set_title(f"Safety check on injected errors ({summary['cases']} drafts, {summary['patients']} Synthea patients): "
                 f"{summary['recall_in_scope']:.0%} in-scope caught, {summary['false_positive_rate']:.0%} clean flagged",
                 fontsize=10)
    ax.spines[["top", "right"]].set_visible(False)
    fig.text(0.01, 0.01, "blue: in-scope errors (higher is better) · dark grey: clean drafts (lower is better) · "
             "light grey: out of scope", fontsize=8, color="#5d6878")
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.savefig(out / "safety-eval.png", dpi=150)
    print(f"\nwrote {out / 'safety-eval.json'} and {out / 'safety-eval.png'}")


if __name__ == "__main__":
    main()
